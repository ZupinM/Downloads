# Writes a binary as a C byte array, in the same layout as the J-Flash "Save as C file" export
# that the bootflasher projects embed (16 bytes per line, upper-case hex, size in the declaration).
#   bin2c.ps1 -Bin <file.bin> -Out <file.c> -Declaration 'const unsigned char _acMicro_bootloader'
param(
    [Parameter(Mandatory)][string]$Bin,
    [Parameter(Mandatory)][string]$Out,
    [Parameter(Mandatory)][string]$Declaration
)
$ErrorActionPreference = 'Stop'
$bytes = [IO.File]::ReadAllBytes($Bin)
$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('/************************************************************************')
[void]$sb.AppendLine('*                                                                       *')
[void]$sb.AppendLine('*               Generated C-File                                        *')
[void]$sb.AppendLine('*                                                                       *')
[void]$sb.AppendLine('*************************************************************************')
[void]$sb.AppendLine('')
[void]$sb.AppendLine("Generated by Downloads\bin2c.ps1 from $(Split-Path $Bin -Leaf) - do not edit.")
[void]$sb.AppendLine('')
[void]$sb.AppendLine(('Memory image: 0x0000 - 0x{0:X4}' -f ($bytes.Length - 1)))
[void]$sb.AppendLine('*/')
[void]$sb.AppendLine('')
[void]$sb.AppendLine(('{0}[0x{1:X}] = {{' -f $Declaration, $bytes.Length))
for ($i = 0; $i -lt $bytes.Length; $i += 16) {
    $n = [Math]::Min(16, $bytes.Length - $i)
    $line = ($bytes[$i..($i + $n - 1)] | ForEach-Object { '0x{0:X2}' -f $_ }) -join ', '
    [void]$sb.AppendLine("  $line,")
}
[void]$sb.AppendLine('};')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('/*** end of file ***/')
[IO.File]::WriteAllText($Out, $sb.ToString().Replace("`r`n", "`n").Replace("`n", "`r`n"))
Write-Host "bin2c: $($bytes.Length) bytes -> $Out"
